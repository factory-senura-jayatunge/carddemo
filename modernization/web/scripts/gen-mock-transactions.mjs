// Writes src/mocks/transactionData.ts from app/data/ASCII/dailytran.txt (layout
// CVTRA06Y), the transactions of the list and view pages in mock mode. Run it
// again only when the sample data changes: node scripts/gen-mock-transactions.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const file = join(web, '../../app/data/ASCII/dailytran.txt');
const lines = readFileSync(file, 'latin1')
  .split('\n')
  .filter((l) => l.trim() !== '');

/** Zoned decimal with the sign overpunched on the last digit, as cents. */
function zoned(field) {
  const last = field.at(-1);
  const positive = '{ABCDEFGHI'.indexOf(last);
  const negative = '}JKLMNOPQR'.indexOf(last);
  const digit = positive >= 0 ? positive : negative >= 0 ? negative : Number(last);
  if (Number.isNaN(digit)) throw new Error(`not zoned decimal: ${field}`);
  const value = Number(field.slice(0, -1) + digit);
  return negative >= 0 ? -value : value;
}

function cut(line, widths) {
  let at = 0;
  return widths.map((width) => {
    const part = line.slice(at, at + width);
    at += width;
    return part;
  });
}

const trim = (s) => s.replace(/ +$/, '');

const rows = lines
  .map((line) => {
    const [tranId, typeCd, catCd, source, description, amount, merchantId, merchantName, merchantCity, merchantZip, cardNum, origTs, procTs] = cut(
      line,
      [16, 2, 4, 10, 100, 11, 9, 50, 50, 10, 16, 26, 26],
    );
    // The daily file has no processing time; transaction-service's sample loader uses the origin time for both.
    const orig = trim(origTs);
    return {
      tranId,
      typeCd: trim(typeCd),
      catCd,
      source: trim(source),
      description: trim(description),
      amount: zoned(amount),
      merchantId,
      merchantName: trim(merchantName),
      merchantCity: trim(merchantCity),
      merchantZip: trim(merchantZip),
      cardNum,
      origTs: orig,
      procTs: trim(procTs) || orig,
    };
  })
  .sort((a, b) => (a.tranId < b.tranId ? -1 : 1));

const out = `// Generated by scripts/gen-mock-transactions.mjs from app/data/ASCII/dailytran.txt. Do not edit.
// Mock mode only. Amounts in cents. Ascending tran_id.

export interface SampleTransaction { tranId: string; typeCd: string; catCd: string; source: string; description: string; amount: number; merchantId: string; merchantName: string; merchantCity: string; merchantZip: string; cardNum: string; origTs: string; procTs: string }

export const sampleTransactions: SampleTransaction[] = ${JSON.stringify(rows, null, 0).replace(/\},\{/g, '},\n  {').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')};
`;
writeFileSync(join(web, 'src/mocks/transactionData.ts'), out);
console.log(`gen-mock-transactions: ${rows.length} transactions`);
