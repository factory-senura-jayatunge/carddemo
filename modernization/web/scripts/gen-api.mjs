// Generates the typed API definitions in src/api/generated/ from the
// committed OpenAPI snapshots in openapi/*.json. Each service's
// OpenApiExportTest keeps its snapshot equal to what the service serves, so
// this needs no Maven run and a contract change is a reviewed diff.
// CARDDEMO_OPENAPI_DIR points at another folder of snapshots (for example a
// service's target/openapi/) to try a contract change before committing it.
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(process.env.CARDDEMO_OPENAPI_DIR ?? join(web, 'openapi'));
const outDir = join(web, 'src/api/generated');
const REQUIRED = ['identity-service', 'billpay-service'];

const files = existsSync(source) ? readdirSync(source).filter((f) => f.endsWith('.json')) : [];
const missing = REQUIRED.filter((name) => !files.includes(`${name}.json`));
if (missing.length) {
  console.error(`gen:api: missing ${missing.map((n) => `${n}.json`).join(', ')} in ${source}`);
  process.exit(1);
}

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
for (const file of files.sort()) {
  const name = basename(file, '.json');
  const ast = await openapiTS(pathToFileURL(join(source, file)));
  const header = `// Generated by scripts/gen-api.mjs from ${relative(web, join(source, file))}. Do not edit.\n\n`;
  writeFileSync(join(outDir, `${name}.ts`), header + astToString(ast));
  console.log(`gen:api: ${name}`);
}
