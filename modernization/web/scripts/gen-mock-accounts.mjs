// Writes src/mocks/accountData.ts from the sample data in app/data/ASCII
// (accounts, customers, cards, card cross-reference), for the account and card
// pages of mock mode. The CVV is never copied (D-DATA-04). Run it again only
// when the sample data changes: node scripts/gen-mock-accounts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ascii = join(web, '../../app/data/ASCII');
const lines = (file) => readFileSync(join(ascii, file), 'latin1').split('\n').filter((l) => l.trim() !== '');

/** Zoned decimal with the sign overpunched on the last digit, as cents. */
function zoned(field) {
  const last = field.at(-1);
  const positive = '{ABCDEFGHI'.indexOf(last);
  const negative = '}JKLMNOPQR'.indexOf(last);
  const digit = positive >= 0 ? positive : negative >= 0 ? negative : Number(last);
  if (Number.isNaN(digit)) throw new Error(`not zoned decimal: ${field}`);
  const value = Number(field.slice(0, -1) + digit);
  return negative >= 0 ? -value : value;
}

function cut(line, widths) {
  let at = 0;
  return widths.map((width) => {
    const part = line.slice(at, at + width);
    at += width;
    return part;
  });
}

const trim = (s) => s.replace(/ +$/, '');

const accounts = lines('acctdata.txt').map((line) => {
  const [acctId, activeStatus, currBal, creditLimit, cashCreditLimit, openDate, expirationDate, reissueDate, currCycCredit, currCycDebit, , groupId] =
    cut(line, [11, 1, 12, 12, 12, 10, 10, 10, 12, 12, 10, 10]);
  return {
    acctId,
    activeStatus,
    currBal: zoned(currBal),
    creditLimit: zoned(creditLimit),
    cashCreditLimit: zoned(cashCreditLimit),
    openDate,
    expirationDate,
    reissueDate,
    currCycCredit: zoned(currCycCredit),
    currCycDebit: zoned(currCycDebit),
    groupId: trim(groupId),
  };
});

const customers = lines('custdata.txt').map((line) => {
  const f = cut(line, [9, 25, 25, 25, 50, 50, 50, 2, 3, 10, 15, 15, 9, 20, 10, 10, 1, 3]);
  const [custId, firstName, middleName, lastName, addrLine1, addrLine2, city, stateCd, countryCd, zip, phone1, phone2, ssn, govtIssuedId, dob, eftAccountId, priCardHolderInd, ficoScore] =
    f.map(trim);
  return { custId, firstName, middleName, lastName, addrLine1, addrLine2, city, stateCd, countryCd, zip, phone1, phone2, ssn, govtIssuedId, dob, eftAccountId, priCardHolderInd, ficoScore: Number(ficoScore) };
});

const cards = lines('carddata.txt').map((line, index) => {
  const [cardNum, acctId, , embossedName, expirationDate, activeStatus] = cut(line, [16, 11, 3, 50, 10, 1]);
  return { cardId: index + 1, cardNum, acctId, embossedName: trim(embossedName), expirationDate, activeStatus };
});

const xref = lines('cardxref.txt').map((line) => {
  const [cardNum, custId, acctId] = cut(line, [16, 9, 11]);
  return { cardNum, custId, acctId };
});

const out = `// Generated by scripts/gen-mock-accounts.mjs from app/data/ASCII. Do not edit.
// Mock mode only. Amounts in cents. No CVV (D-DATA-04).

export interface SampleAccount { acctId: string; activeStatus: string; currBal: number; creditLimit: number; cashCreditLimit: number; openDate: string; expirationDate: string; reissueDate: string; currCycCredit: number; currCycDebit: number; groupId: string }
export interface SampleCustomer { custId: string; firstName: string; middleName: string; lastName: string; addrLine1: string; addrLine2: string; city: string; stateCd: string; countryCd: string; zip: string; phone1: string; phone2: string; ssn: string; govtIssuedId: string; dob: string; eftAccountId: string; priCardHolderInd: string; ficoScore: number }
export interface SampleCard { cardId: number; cardNum: string; acctId: string; embossedName: string; expirationDate: string; activeStatus: string }
export interface SampleXref { cardNum: string; custId: string; acctId: string }

export const sampleAccounts: SampleAccount[] = ${JSON.stringify(accounts, null, 0).replace(/\},\{/g, '},\n  {').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')};

export const sampleCustomers: SampleCustomer[] = ${JSON.stringify(customers, null, 0).replace(/\},\{/g, '},\n  {').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')};

export const sampleCards: SampleCard[] = ${JSON.stringify(cards, null, 0).replace(/\},\{/g, '},\n  {').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')};

export const sampleXref: SampleXref[] = ${JSON.stringify(xref, null, 0).replace(/\},\{/g, '},\n  {').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')};
`;
writeFileSync(join(web, 'src/mocks/accountData.ts'), out);
console.log(`gen-mock-accounts: ${accounts.length} accounts, ${customers.length} customers, ${cards.length} cards, ${xref.length} xref rows`);
