// Writes src/messages.ts from the message catalogue that platform/web-support
// exports (target/messages.json), so the web app shows the same texts as the
// services. With --check it only compares and fails on a difference.
//
// Accepted shapes of messages.json:
//   { "CODE": { "text": "...", "severity": "error" }, ... }
//   { "CODE": "..." }                       (severity defaults to error)
//   [ { "code": "CODE", "message"|"text": "...", "severity": "..." }, ... ]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(
  process.env.CARDDEMO_MESSAGES_JSON ?? join(web, '../platform/web-support/target/messages.json'),
);
const target = join(web, 'src/messages.ts');
const check = process.argv.includes('--check');

if (!existsSync(source)) {
  console.error(`gen:messages: ${source} not found; build platform/web-support first (./mvnw -pl platform/web-support package)`);
  process.exit(2);
}

const raw = JSON.parse(readFileSync(source, 'utf8'));
const entries = Array.isArray(raw)
  ? raw.map((m) => [m.code, { text: m.text ?? m.message, severity: m.severity ?? 'error' }])
  : Object.entries(raw).map(([code, m]) => [code, typeof m === 'string' ? { text: m, severity: 'error' } : { text: m.text ?? m.message, severity: m.severity ?? 'error' }]);
entries.sort(([a], [b]) => a.localeCompare(b));

const body = entries
  .map(([code, m]) => `  ${code}: { text: ${JSON.stringify(m.text)}, severity: '${m.severity}' },`)
  .join('\n');
const output = `// Generated by scripts/gen-messages.mjs from platform/web-support's message catalogue. Do not edit.
// Placeholders such as {name} are filled in by fillMessage() in src/lib/messages.ts.

export const messages = {
${body}
} as const satisfies Record<string, { text: string; severity: 'error' | 'success' | 'info' }>;

export type MessageCode = keyof typeof messages;
`;

if (check) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== output) {
    console.error('gen:messages: src/messages.ts differs from the catalogue; run npm run gen:messages');
    process.exit(1);
  }
  console.log('gen:messages: OK');
} else {
  writeFileSync(target, output);
  console.log(`gen:messages: ${entries.length} messages`);
}
