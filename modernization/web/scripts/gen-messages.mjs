// Writes src/messages/ from the message catalogue that platform/web-support exports
// (target/messages.json, written by MessageCatalogTest), so the web app shows the same texts as the
// services. The catalogue is split by scripts/message-groups.mjs into one table per group, a
// types-only index and a merged table for the mocks. With --check it only compares and fails on a
// difference; --if-present skips the check when the export has not been built (a web-only checkout),
// unless CARDDEMO_MESSAGES_JSON names it.
//
// messages.json: { "<key>": { "code", "text", "severity", "params", "source" }, ... }
// in catalogue order. Several keys may share one API code (variants of a text,
// such as NEW_PASSWORD_LENGTH_LEGACY and NEW_PASSWORD_LENGTH_FIXED).
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ENTRY_GROUPS, GROUPS, groupOf } from './message-groups.mjs';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(
  process.env.CARDDEMO_MESSAGES_JSON ?? join(web, '../platform/web-support/target/messages.json'),
);
const dir = join(web, 'src/messages');
const legacy = join(web, 'src/messages.ts');
const check = process.argv.includes('--check');
const ifPresent = process.argv.includes('--if-present') && !process.env.CARDDEMO_MESSAGES_JSON;
const HEADER = "// Generated by scripts/gen-messages.mjs from platform/web-support's message catalogue. Do not edit.";

if (!existsSync(source) && check && ifPresent) {
  console.log(`gen:messages: SKIPPED, ${source} not built (./mvnw -pl platform/web-support test -Dtest=MessageCatalogTest)`);
  process.exit(0);
}
if (!existsSync(source)) {
  console.error(
    `gen:messages: ${source} not found; build it with ./mvnw -pl platform/web-support test -Dtest=MessageCatalogTest (or set CARDDEMO_MESSAGES_JSON)`,
  );
  process.exit(2);
}

const raw = JSON.parse(readFileSync(source, 'utf8'));
const SEVERITIES = new Set(['error', 'success', 'info']);
const problems = [];
const groups = new Map(GROUPS.map((group) => [group, []]));
for (const [key, m] of Object.entries(raw)) {
  if (!/^[A-Z][A-Z0-9_]*$/.test(key)) problems.push(`${key}: key is not UPPER_SNAKE`);
  if (typeof m?.code !== 'string' || typeof m.text !== 'string') problems.push(`${key}: code and text must be strings`);
  if (!SEVERITIES.has(m?.severity)) problems.push(`${key}: unknown severity ${m?.severity}`);
  if (typeof m?.source !== 'string') problems.push(`${key}: source must be a string`);
  const params = Array.isArray(m?.params) ? m.params : [];
  const inText = [...String(m?.text ?? '').matchAll(/\{([A-Za-z]+)\}/g)].map((p) => p[1]);
  if (JSON.stringify(inText) !== JSON.stringify(params)) problems.push(`${key}: params ${JSON.stringify(params)} do not match the text`);
  let group;
  try {
    group = groupOf(key, String(m?.source));
  } catch (error) {
    problems.push(error.message);
    continue;
  }
  if (!groups.has(group)) problems.push(`${key}: group ${group} is not in GROUPS`);
  else groups.get(group).push([key, { code: m.code, text: m.text, severity: m.severity, params }]);
}
if (problems.length) {
  console.error(`gen:messages: ${source} is not a valid catalogue:\n  ${problems.join('\n  ')}`);
  process.exit(2);
}

const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const cap = (s) => s[0].toUpperCase() + s.slice(1);
const used = GROUPS.filter((group) => groups.get(group).length > 0);
const files = new Map();
for (const group of used) {
  const body = groups
    .get(group)
    .map(([key, m]) => `  ${key}: { code: ${q(m.code)}, text: ${q(m.text)}, severity: ${q(m.severity)}, params: [${m.params.map(q).join(', ')}] },`)
    .join('\n');
  const where = ENTRY_GROUPS.includes(group) ? 'It loads with the entry.' : 'It loads only with the pages that import it.';
  files.set(
    `${group}.ts`,
    `${HEADER}
// The ${group} group of the catalogue (scripts/message-groups.mjs). ${where}
// Keys are catalogue keys; code is the API code, which variants of a text share.
// Placeholders such as {name} are filled in by src/lib/messages.ts.

export const ${group}Messages = {
${body}
} as const satisfies Record<string, { code: string; text: string; severity: 'error' | 'success' | 'info'; params: readonly string[] }>;
`,
  );
}
const entryUsed = used.filter((group) => ENTRY_GROUPS.includes(group));
files.set(
  'index.ts',
  `${HEADER}
// Types only: importing a message type never puts a table in a chunk. The tables are in the group
// files; src/lib/messages.ts holds the entry groups (${ENTRY_GROUPS.join(', ')}), and a lazy page imports its own.
${used.map((group) => `import type { ${group}Messages } from './${group}';`).join('\n')}

export interface MessageEntry {
  readonly code: string;
  readonly text: string;
  readonly severity: 'error' | 'success' | 'info';
  readonly params: readonly string[];
}
export type MessageTable = Readonly<Record<string, MessageEntry>>;

${used.map((group) => `export type ${cap(group)}Key = keyof typeof ${group}Messages;`).join('\n')}

/** The keys that src/lib/messages.ts resolves without a page table. */
export type EntryKey = ${entryUsed.map((group) => `${cap(group)}Key`).join(' | ')};
export type MessageKey = ${used.map((group) => `${cap(group)}Key`).join(' | ')};
export type MessageCode = (${used.map((group) => `typeof ${group}Messages`).join(' & ')})[MessageKey]['code'];
`,
);
files.set(
  'all.ts',
  `${HEADER}
// Every group in one table, for the mocks and tests only; eslint keeps it out of the app.
${used.map((group) => `import { ${group}Messages } from './${group}';`).join('\n')}

export const messages = {
${used.map((group) => `  ...${group}Messages,`).join('\n')}
};
`,
);

const generated = (path) => existsSync(path) && readFileSync(path, 'utf8').startsWith(HEADER);
const present = existsSync(dir) ? readdirSync(dir) : [];
const extra = present.filter((name) => !files.has(name));
const counts = used.map((group) => `${group} ${groups.get(group).length}`).join(', ');
const total = Object.keys(raw).length;

if (check) {
  const stale = [...files].filter(([name, text]) => !existsSync(join(dir, name)) || readFileSync(join(dir, name), 'utf8') !== text).map(([name]) => name);
  const reasons = [
    ...stale.map((name) => `src/messages/${name} differs from the catalogue`),
    ...extra.map((name) => `src/messages/${name} is not generated from the catalogue`),
    ...(existsSync(legacy) ? ['src/messages.ts is the old single table'] : []),
  ];
  if (reasons.length) {
    console.error(`gen:messages: ${reasons.join('; ')}; run npm run gen:messages`);
    process.exit(1);
  }
  console.log(`gen:messages: OK (${total} messages: ${counts})`);
} else {
  const foreign = extra.filter((name) => !generated(join(dir, name)));
  if (foreign.length) {
    console.error(`gen:messages: src/messages/ holds files it did not write: ${foreign.join(', ')}`);
    process.exit(2);
  }
  mkdirSync(dir, { recursive: true });
  for (const name of extra) rmSync(join(dir, name));
  if (generated(legacy)) rmSync(legacy);
  for (const [name, text] of files) writeFileSync(join(dir, name), text);
  console.log(`gen:messages: ${total} messages: ${counts}`);
}
