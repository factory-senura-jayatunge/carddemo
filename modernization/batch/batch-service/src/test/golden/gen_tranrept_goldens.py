#!/usr/bin/env python3
"""Regenerate the golden files of the TRANREPT report writer tests.

Every expected report comes from the original CBTRN03C, run with the GnuCOBOL
build through docs/modernization/spec/checks/d1_harness.py, never from the Java
writer. The inputs are the ones the spec-only equivalence check uses
(docs/modernization/spec/checks/tranrept_reimpl):

  sample-posttran  the sample data after POSTTRAN, filtered to the JCL range
                   and sorted by card number (run_check.prepare), with the
                   job's DATEPARM record
  case-*           the edge cases of tranrept_reimpl/gen_stress.py

One folder per case under src/test/resources/tranrept/:

  tranfile.txt.gz      the sorted TRANFILE: 350-byte records, no separators
  dateparm.txt         the DATEPARM record as given to the program
  TRANREPT.txt.gz      the program's report: 133-byte lines, each followed by LF
                       (absent when the program wrote none)
  expected.properties  return code, line count, length and SHA-256, and how the
                       Java test uses the case (java=same, java=REPORT_REFERENCE_MISSING:
                       <lookup>, or java=not-compared with the reason)

The reference files (cardxref.txt, trantype.txt, trancatg.txt) are those of
app/data/ASCII, which every case uses unchanged.

Usage: make build, then python3 gen_tranrept_goldens.py   (needs cobc on PATH)
"""
from __future__ import annotations

import gzip
import hashlib
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[6]
CHECKS = ROOT / "docs/modernization/spec/checks"
sys.path.insert(0, str(CHECKS))
sys.path.insert(0, str(CHECKS / "tranrept_reimpl"))
import d1_harness  # noqa: E402
import gen_stress  # noqa: E402
from run_check import prepare  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "resources" / "tranrept"
HEADER = "# Generated by src/test/golden/gen_tranrept_goldens.py from CBTRN03C; do not edit.\n"
SAMPLE = ROOT / "app" / "data" / "ASCII"
LINE = 133

# How the Java test uses each case. Every other case must be java=same.
USES = {
    "case-badcat": "REPORT_REFERENCE_MISSING: transaction category",
    "case-badcard": "REPORT_REFERENCE_MISSING: card cross-reference",
    "case-blankdates": "not-compared: blank DATEPARM dates; report_run stores two DATE values",
    "case-blankcard": "not-compared: a blank card number has no cross-reference row; the program prints an "
                      "account ID it never read",
}
DESCRIPTIONS = {
    "sample-posttran": "the sample data after POSTTRAN in the JCL range, sorted by card number",
    "case-main": "many cards, range bounds, negative and zero totals, an overflowing grand total, an "
                 "out-of-range record late in the file (the report stops there)",
    "case-allin": "case-main without the out-of-range record",
    "case-lastout": "the last record is out of range (no totals)",
    "case-empty": "an empty TRANFILE",
    "case-reversed": "start date after end date",
    "case-blankdates": "an empty TRANFILE with blank DATEPARM dates",
    "case-blankcard": "the first record has a blank card number",
    "case-badcat": "a category missing from TRANCATG",
    "case-badcard": "a card missing from CARDXREF",
}


def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def gz(path: Path, data: bytes) -> None:
    path.write_bytes(gzip.compress(data, mtime=0))


def report_bytes(out: Path) -> bytes:
    lines = d1_harness.split_lines(out / "TRANREPT.txt")
    for n, line in enumerate(lines, 1):
        if len(line) != LINE:
            raise SystemExit(f"{out.name}: report line {n} has {len(line)} characters")
    return "".join(line + "\n" for line in lines).encode("latin-1")


def record(name: str, data: Path, out: Path) -> None:
    rc = d1_harness.run_reference("TRANREPT", data, out)
    tran = b"".join(d1_harness.carddemo.read_text_records(data / "tranfile.txt", 350))
    report = report_bytes(out)
    use = USES.get(name, "same")
    if use == "same" and rc != 0:
        raise SystemExit(f"{name}: rc={rc}")
    if use.startswith("REPORT_REFERENCE_MISSING") and rc == 0:
        raise SystemExit(f"{name}: the program did not abend")
    folder = OUT / name
    if folder.exists():
        shutil.rmtree(folder)
    folder.mkdir(parents=True)
    gz(folder / "tranfile.txt.gz", tran)
    shutil.copy(data / "dateparm.txt", folder / "dateparm.txt")
    if report:
        gz(folder / "TRANREPT.txt.gz", report)
    props = [f"description={DESCRIPTIONS[name]}", f"java={use}", f"cobol.rc={rc}",
             f"records={len(tran) // 350}", f"lines={len(report) // (LINE + 1)}",
             f"length={len(report)}", f"sha256={sha(report)}"]
    (folder / "expected.properties").write_text(HEADER + "\n".join(props) + "\n")
    print(f"{name}: rc={rc}, {len(tran) // 350} records, {len(report) // (LINE + 1)} lines")


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        data = tmp / "sample-posttran"
        shutil.copytree(SAMPLE, data)
        prepare(data, tmp / "sample-pre")
        record("sample-posttran", data, tmp / "sample-posttran-out")
        stress = tmp / "stress"
        argv = sys.argv
        sys.argv = [argv[0], str(stress)]
        try:
            gen_stress.main()
        finally:
            sys.argv = argv
        for case in sorted(p for p in stress.iterdir() if p.is_dir()):
            if case.name not in DESCRIPTIONS:
                raise SystemExit(f"{case.name}: no description; add it to DESCRIPTIONS")
            record(case.name, case, tmp / f"{case.name}-out")
    return 0


if __name__ == "__main__":
    sys.exit(main())
