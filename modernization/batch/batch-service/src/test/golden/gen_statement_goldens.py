def case_total_overflow() -> dict:
    customers = [plain_customer(1), plain_customer(2)]
    accounts = [account(1, 999999999999), account(2, -100000000000)]
    xrefs = [xref(card(1), 1, 1), xref(card(2), 2, 2), xref(card(3), 1, 1)]
    trans = [tran(f"00000000000001{j:02d}", card(1), "Large purchase", 99999999999) for j in range(10)]
    trans += [tran("0000000000000201", card(2), "Large purchase", 99999999999),
              tran("0000000000000202", card(2), "Small purchase", 1),
              tran("0000000000000203", card(2), "Small refund", -1),
              tran("0000000000000301", card(3), "Large refund", -99999999999),
              tran("0000000000000302", card(3), "Small refund", -1)]
    return {"description": "statement totals beyond 999,999,999.99 (NUM-STMT-004) and the largest balances "
                           "(DEF-STMT-004)",
            "xref": xrefs, "cust": customers, "acct": accounts, "tran": trans}


def case_max_table() -> dict:
    customers = [plain_customer(i) for i in range(1, 53)]
    accounts = [account(i, (i * 7919 % 2000000) - 300000) for i in range(1, 53)]
    xrefs = [xref(card(i), i, i) for i in range(1, 53)]
    trans = []
    for i in range(1, 52):
        for j in range(1, 11):
            cents = ((i * 10 + j) * 1234567) % 100000000 - 50000000
            trans.append(tran(f"{i:02d}{j:014d}", card(i), f"Fake purchase {i:02d}-{j:02d}", cents))
    trans.sort(key=lambda r: r[:16])
    return {"description": "the table limit exactly: 51 cards of 10 transactions, and a 52nd cross-reference "
                           "card without transactions, which takes no slot",
            "xref": xrefs, "cust": customers, "acct": accounts, "tran": trans}


def case_orphan_only() -> dict:
    return {"description": "two cards without transactions; the only transaction is on a card outside the "
                           "cross-reference, so the output is that of an empty work file",
            "xref": [xref(card(1), 1, 1), xref(card(2), 2, 2)],
            "cust": [plain_customer(1), plain_customer(2)], "acct": [account(1, 1000), account(2, -1000)],
            "tran": [tran("0000000000009001", card(90), "Orphan", 100)]}


def case_over_cards() -> dict:
    return {"description": "52 cards with one transaction each, one card slot more than the table",
            "xref": [xref(card(i), i, i) for i in range(1, 53)],
            "cust": [plain_customer(i) for i in range(1, 53)], "acct": [account(i, 1000 * i) for i in range(1, 53)],
            "tran": [tran(f"{i:02d}00000000000001", card(i), "Fake purchase", 100 * i) for i in range(1, 53)]}


def over_transactions(first: int, second: int, where: str) -> dict:
    trans = [tran(f"01{j:014d}", card(1), f"Fake purchase {j:02d}", 100 * j) for j in range(1, first + 1)]
    trans += [tran(f"02{j:014d}", card(2), f"Fake purchase {j:02d}", 100 * j) for j in range(1, second + 1)]
    return {"description": f"11 transactions on the {where} card, one transaction slot more than the table",
            "xref": [xref(card(1), 1, 1), xref(card(2), 2, 2)],
            "cust": [plain_customer(1), plain_customer(2)], "acct": [account(1, 1000), account(2, 2000)],
            "tran": trans}


CASES = {
    "edge": (case_edge, True),
    "total-overflow": (case_total_overflow, True),
    "max-table": (case_max_table, True),
    "orphan-only": (case_orphan_only, True),
    "over-cards": (case_over_cards, False),
    "over-transactions": (lambda: over_transactions(11, 1, "first"), False),
    "over-transactions-last": (lambda: over_transactions(1, 11, "last"), False),
}


# harness -----------------------------------------------------------------
def run_harness(out: Path, data: Path | None = None) -> dict:
    cmd = [sys.executable, str(HARNESS), str(out)] + (["--data", str(data)] if data else [])
    subprocess.run(cmd, check=True, capture_output=True, text=True)
    rc = int((out / "rc.txt").read_text().strip())
    def read(name: str) -> bytes:
        p = out / name
        return p.read_bytes() if p.exists() else b""
    return {"rc": rc, "text": read("STMTFILE"), "html": read("HTMLFILE")}


def statements(data: bytes, lrecl: int, start: bytes) -> list[bytes]:
    recs = [data[i:i + lrecl] for i in range(0, len(data), lrecl)]
    out: list[list[bytes]] = []
    for r in recs:
        if r.startswith(start) or not out:
            out.append([])
        out[-1].append(r)
    return [b"".join(s) for s in out]


def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def summary(res: dict, per_statement: bool) -> list[str]:
    lines = [f"cobol.rc={res['rc']}"]
    text, html = res["text"], res["html"]
    st, sh = statements(text, 80, TEXT_START), statements(html, 100, HTML_START)
    if len(st) != len(sh):
        raise SystemExit(f"text has {len(st)} statements, HTML {len(sh)}")
    lines += [f"statements={len(st)}",
              f"text.records={len(text) // 80}", f"text.length={len(text)}", f"text.sha256={sha(text)}",
              f"html.records={len(html) // 100}", f"html.length={len(html)}", f"html.sha256={sha(html)}"]
    if per_statement:
        lines += [f"text.statement.{i}={sha(s)}" for i, s in enumerate(st, 1)]
        lines += [f"html.statement.{i}={sha(s)}" for i, s in enumerate(sh, 1)]
    return lines


def write_properties(folder: Path, lines: list[str]) -> None:
    (folder / "expected.properties").write_text(HEADER + "\n".join(lines) + "\n")


def gz(path: Path, data: bytes) -> None:
    path.write_bytes(gzip.compress(data, mtime=0))


def sample(tmp: Path) -> None:
    work = carddemo.WorkDir.fresh(tmp / "posttran")
    res = work.run_job(carddemo.JOBS["POSTTRAN"])
    if res.rc not in (0, 4):
        raise SystemExit(f"POSTTRAN rc={res.rc}")
    transact = work.unload_ksds("TRANSACT")
    accounts = work.unload_ksds("ACCTDATA")
    daily = {r[:16]: r for r in carddemo.read_text_records(carddemo.data_dir() / "dailytran.txt", 350)}
    for r in transact:
        d = daily[r[:16]]
        for lo, hi in ((0, 16), (32, 143), (262, 278)):
            if r[lo:hi] != d[lo:hi]:
                raise SystemExit("a posted transaction differs from its daily record in a printed field")
    data = tmp / "sample-data"
    data.mkdir()
    carddemo.write_fixed(data / "TRANSACT.ps", transact, 350)
    carddemo.write_fixed(data / "ACCTDATA.ps", accounts, 300)
    for name, src, lrecl in (("CARDXREF", "cardxref.txt", 50), ("CUSTDATA", "custdata.txt", 500)):
        carddemo.write_fixed(data / f"{name}.ps", carddemo.read_text_records(carddemo.data_dir() / src, lrecl),
                             lrecl)
    by_default = run_harness(tmp / "sample-default")
    by_data = run_harness(tmp / "sample-by-data", data)
    if (by_default["text"], by_default["html"]) != (by_data["text"], by_data["html"]):
        raise SystemExit("the committed POSTTRAN results do not reproduce the harness default")
    folder = OUT / "sample-posttran"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "posted-tran-ids.txt").write_bytes(b"".join(r[:16] + b"\n" for r in transact))
    (folder / "acctdata-after-posttran.txt").write_bytes(b"".join(r + b"\n" for r in accounts))
    write_properties(folder, ["description=the harness default: the sample data after POSTTRAN",
                              f"posted={len(transact)}"] + summary(by_default, True))
    print(f"sample-posttran: {len(transact)} posted, rc={by_default['rc']}")


def synthetic(tmp: Path, name: str, build, renders: bool) -> None:
    c = build()
    data = tmp / f"{name}-data"
    data.mkdir()
    files = {"CARDXREF": c["xref"], "CUSTDATA": c["cust"], "ACCTDATA": c["acct"], "TRANSACT": c["tran"]}
    for ds, recs in files.items():
        (data / f"{ds}.ps").write_bytes(b"".join(recs))
    res = run_harness(tmp / f"{name}-out", data)
    folder = OUT / name
    if folder.exists():
        shutil.rmtree(folder)
    folder.mkdir(parents=True)
    for ds in files:
        gz(folder / f"{ds}.ps.gz", (data / f"{ds}.ps").read_bytes())
    lines = [f"description={c['description']}"]
    if renders:
        if res["rc"] != 0:
            raise SystemExit(f"{name}: harness rc={res['rc']}")
        lines += summary(res, False)
        gz(folder / "STMTFILE.gz", res["text"])
        gz(folder / "HTMLFILE.gz", res["html"])
    else:
        lines += ["expected=STATEMENT_TABLE_LIMIT", f"observed.cobol.rc={res['rc']}",
                  f"observed.text.records={len(res['text']) // 80}",
                  f"observed.html.records={len(res['html']) // 100}"]
    write_properties(folder, lines)
    print(f"{name}: rc={res['rc']}, text {len(res['text'])} bytes, html {len(res['html'])} bytes")


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        sample(Path(tmp))
        for name, (build, renders) in CASES.items():
            synthetic(Path(tmp), name, build, renders)
    return 0


if __name__ == "__main__":
    sys.exit(main())
