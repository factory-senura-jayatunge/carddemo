#!/usr/bin/env python3
"""Regenerate the golden files of the legacy statement renderer tests.

Every expected statement comes from the original CBSTM03A, run through
docs/modernization/spec/checks/cbstm03a_harness/run_harness.py (GnuCOBOL with
only the z/OS TIOT prologue commented out), never from the Java renderer.

Cases, one folder each under src/test/resources/statement/:

  sample-posttran   The harness default: the sample data after POSTTRAN. The
                    outputs are pinned by length and SHA-256, per file and per
                    statement, and not committed. The inputs are the sample
                    files plus what POSTTRAN changed: posted-tran-ids.txt (the
                    daily transactions it posted; card, ID, description and
                    amount are those of dailytran.txt, which this script checks)
                    and acctdata-after-posttran.txt (the account file after the
                    run, one record per line as in app/data/ASCII).
  edge, total-overflow, max-table, orphan-only
                    Fake inputs (gzip of the fixed records run_harness.py --data
                    takes) and the harness outputs (gzip), which are small.
  over-cards, over-transactions, over-transactions-last
                    Beyond the 51 x 10 table (DEF-STMT-001): fake inputs only.
                    What the program did is recorded as observed.* for the
                    record; the renderer refuses these inputs.

Usage: make build, then python3 gen_statement_goldens.py   (needs cobc on PATH)
"""
from __future__ import annotations

import gzip
import hashlib
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[6]
sys.path.insert(0, str(ROOT / "tools"))
import carddemo  # noqa: E402

HARNESS = ROOT / "docs/modernization/spec/checks/cbstm03a_harness/run_harness.py"
OUT = Path(__file__).resolve().parents[1] / "resources" / "statement"
TEXT_START = b"*" * 31 + b"START OF STATEMENT" + b"*" * 31
HTML_START = b"<!DOCTYPE html>"
HEADER = "# Generated by src/test/golden/gen_statement_goldens.py from the CBSTM03A harness; do not edit.\n"


# fixed records -----------------------------------------------------------
def t(value: str, n: int) -> bytes:
    b = value.encode("latin-1")
    if len(b) > n:
        raise ValueError(f"{value!r} is longer than {n}")
    return b.ljust(n, b" ")


def zoned(cents: int, digits: int, negative_zero: bool = False) -> bytes:
    s = f"{abs(cents):0{digits}d}"
    if len(s) != digits:
        raise ValueError(f"{cents} does not fit {digits} digits")
    d = int(s[-1])
    sign = "}JKLMNOPQR"[d] if cents < 0 or negative_zero else "{ABCDEFGHI"[d]
    return (s[:-1] + sign).encode()


def card(n: int) -> str:
    return f"99990000000000{n:02d}"


def xref(card_num: str, cust: int, acct: int) -> bytes:
    return t(card_num, 16) + f"{cust:09d}".encode() + f"{acct:011d}".encode() + b" " * 14


def customer(cid: int, first: str, middle: str, last: str, a1: str, a2: str, a3: str,
             state: str, country: str, zipc: str, fico: int) -> bytes:
    rec = (f"{cid:09d}".encode() + t(first, 25) + t(middle, 25) + t(last, 25)
           + t(a1, 50) + t(a2, 50) + t(a3, 50) + t(state, 2) + t(country, 3) + t(zipc, 10)
           + t("(555)555-0100", 15) + t("(555)555-0199", 15) + b"000000000" + t("FAKE-ID", 20)
           + t("1990-01-01", 10) + t("0000000000", 10) + b"Y" + f"{fico:03d}".encode() + b" " * 168)
    assert len(rec) == 500
    return rec


def account(aid: int, bal_cents: int) -> bytes:
    rec = (f"{aid:011d}".encode() + b"Y" + zoned(bal_cents, 12) + zoned(500000, 12) + zoned(100000, 12)
           + b"2020-01-01" + b"2030-12-31" + b"2025-01-01" + zoned(0, 12) + zoned(0, 12)
           + t("00000", 10) + t("A000000000", 10) + b" " * 178)
    assert len(rec) == 300
    return rec


def tran(tid: str, card_num: str, desc: str, cents: int, negative_zero: bool = False) -> bytes:
    rec = (t(tid, 16) + b"01" + b"0001" + t("POS TERM", 10) + t(desc, 100)
           + zoned(cents, 11, negative_zero) + b"000000001" + t("Fake Merchant", 50) + t("Faketown", 50)
           + t("00000", 10) + t(card_num, 16) + t("2022-07-01 10:00:00.000000", 26)
           + t("2022-07-06 10:00:00.000000", 26) + b" " * 20)
    assert len(rec) == 350
    return rec


def plain_customer(cid: int) -> bytes:
    return customer(cid, f"First{cid:02d}", "Q", f"Last{cid:02d}", f"{cid} Fake Street", "",
                    "Faketown", "WA", "USA", "98101", 600 + cid)


